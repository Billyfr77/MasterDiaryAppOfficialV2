const sentinelService = require('../services/sentinelService');
const db = require('../models');
const { Diary, Quote, Project, AuditLog } = db;
const { logAudit } = require('../services/auditService');
// Safely load Notification model
const Notification = db.Notification || require('../models/notification')(db.sequelize, db.Sequelize.DataTypes);

const runScan = async (req, res) => {
    try {
        const { diaryId } = req.body;
        const result = await sentinelService.processDiary(diaryId, req.user.id);
        res.json(result || { message: "No leakage detected." });
    } catch (error) {
        res.status(500).json({ error: error.message });
    }
};

const runDeepProjectScan = async (req, res) => {
    try {
        const { projectId } = req.body;
        if (!projectId) return res.status(400).json({ error: "ProjectId is required for Deep Scan" });
        
        const result = await sentinelService.performGlobalProjectScan(projectId, req.user.id);
        
        // Log high-value audit event
        await logAudit(req.user.id, 'SENTINEL_DEEP_SCAN_COMPLETE', 'Project', projectId, {
            revenueUnlocked: result.totalRevenueUnlocked,
            diariesScanned: result.diariesScanned
        });

        res.json({ 
            message: `Deep Scan Complete. Found $${result.totalRevenueUnlocked.toLocaleString()} in unbilled work.`, 
            result 
        });
    } catch (error) {
        res.status(500).json({ error: error.message });
    }
};

