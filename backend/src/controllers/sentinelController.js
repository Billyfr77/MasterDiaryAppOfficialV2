const deleteAlert = async (req, res) => {
    try {
        const alert = await Notification.findOne({
            where: { id: req.params.id, userId: req.user.id, type: 'sentinel_alert' }
        });

        if (!alert) return res.status(404).json({ error: "Alert not found" });

        const data = alert.data;
        const rows = await Notification.destroy({
            where: { id: req.params.id, userId: req.user.id }
        });

        if (rows > 0) {
            // Log the deletion
            await logAudit(req.user.id, 'SENTINEL_ALERT_PURGED', 'Notification', req.params.id, {
                projectName: data?.projectName,
                revenueAmount: data?.totalPotentialRevenue
            });
            res.json({ success: true });
        } else {
            res.status(404).json({ error: "Alert not found" });
        }
    } catch (error) {
        res.status(500).json({ error: error.message });
    }
};

const clearHistory = async (req, res) => {
    try {
        const count = await Notification.count({
            where: { userId: req.user.id, type: 'sentinel_alert', isRead: true }
        });

        await Notification.destroy({
            where: { userId: req.user.id, type: 'sentinel_alert', isRead: true }
        });

        await logAudit(req.user.id, 'SENTINEL_HISTORY_CLEARED', 'System', 'Sentinel', {
            recordsCleared: count
        });

        res.json({ success: true });
    } catch (error) {
        res.status(500).json({ error: error.message });
    }
};

